export type I18nKey = keyof (typeof strings)["es"];

export function t(locale: Locale, key: I18nKey): string {
  return strings[locale][key] ?? strings.es[key];
}

export function toggleLocale(locale: Locale): Locale {
  return locale === "es" ? "en" : "es";
}

export function localeFromTenant(tenantLocale?: string): Locale {
  return tenantLocale?.startsWith("en") ? "en" : "es";
}
